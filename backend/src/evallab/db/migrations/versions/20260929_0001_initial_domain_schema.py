TRANSITION_FUNCTION = """
CREATE FUNCTION enforce_status_transition() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    i integer;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status IS DISTINCT FROM TG_ARGV[0] THEN
            RAISE EXCEPTION 'invalid initial status on %: %', TG_TABLE_NAME, NEW.status
                USING ERRCODE = 'check_violation';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.status IS NOT DISTINCT FROM OLD.status THEN
        RETURN NEW;
    END IF;
    FOR i IN 1 .. TG_NARGS - 1 LOOP
        IF TG_ARGV[i] = OLD.status || '>' || NEW.status THEN
            RETURN NEW;
        END IF;
    END LOOP;
    RAISE EXCEPTION 'invalid status transition on %: % -> %',
        TG_TABLE_NAME, OLD.status, NEW.status
        USING ERRCODE = 'check_violation';
END;
$$
"""


def _create_status_triggers() -> None:
    op.execute(TRANSITION_FUNCTION)
    for table, (initial, transitions) in LIFECYCLES.items():
        args = ", ".join(f"'{value}'" for value in (initial, *transitions))
        op.execute(
            f"CREATE TRIGGER {table}_status_transition"
            f" BEFORE INSERT OR UPDATE OF status ON {table}"
            f" FOR EACH ROW EXECUTE FUNCTION enforce_status_transition({args})"
        )


